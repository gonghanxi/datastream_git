double RADAR_TargetScatterLocation::base_random_rcs_(unsigned long long blockIndex, int scatterIndex) const
{
	// RCS 随机基序列由黑盒 RR3/RR4 反推。
	// RCS_out = RCS + RCS_Variance * baseRandom。
	// 前三项对应 RR3-1 的 10.411、9.811、10.922。
	static const double table[] =
	{
		0.41125,
		-0.18900,
		0.92200,
		-0.75600,
		0.33700,
		-0.50800,
		0.61400,
		-0.27100,
		0.14300,
		-0.43600
	};

	const unsigned long long nTable = static_cast<unsigned long long>(sizeof(table) / sizeof(table[0]));
	if (blockIndex < nTable)
		return table[blockIndex];

	unsigned long long x = 1099511628211ULL * static_cast<unsigned long long>(scatterIndex + 1);
	x ^= (blockIndex + 0x9e3779b97f4a7c15ULL);
	x ^= x >> 12;
	x ^= x << 25;
	x ^= x >> 27;
	const unsigned long long y = x * 2685821657736338717ULL;
	const double u = (static_cast<double>((y >> 11) & 0x1FFFFFFFFFFFFFULL) + 1.0)
		/ 9007199254740992.0;
	return 2.0 * u - 1.0;
}

double RADAR_TargetScatterLocation::calc_scatter_rcs_(int idx, unsigned long long k) const
{
	const double base = get_rcs_base_(idx);

	if (IsRCSRandom != RCSRandom_true)
		return base;

	// 黑盒 RR5：DurationTime 不自动广播。某个 scatter 没有对应 DurationTime 时，不产生随机 RCS。
	if (DurationTime == nullptr || idx < 0 || idx >= DurationTimeSize)
		return base;

	if (RCS_Variance == nullptr || idx >= RCS_VarianceSize)
		return base;

	const double variance = RCS_Variance[idx];
	if (variance == 0.0)
		return base;

	const double dur = DurationTime[idx];
	if (dur <= 0.0 || TimeStep <= 0.0)
		return base;

	// DurationTime 以秒为单位。换算成 sample 数。
	// 黑盒结果：DurationTime=1, TimeStep=1 时 k=0,1 保持基准；k=2 开始第一个随机值。
	// DurationTime=3, TimeStep=1 时 k=0..3 保持基准；k=4..6 为第一个随机值。
	long long durSamples = static_cast<long long>(std::floor(dur / TimeStep + 1.0e-12));
	if (durSamples < 1)
		durSamples = 1;

	const unsigned long long holdSamples = static_cast<unsigned long long>(durSamples + 1);
	if (k < holdSamples)
		return base;

	const unsigned long long blockIndex = (k - holdSamples) / static_cast<unsigned long long>(durSamples);
	return base + variance * base_random_rcs_(blockIndex, idx);
}

void RADAR_TargetScatterLocation::write_outputs_(const std::vector<Vec3>& positions, const std::vector<double>& rcsValues)
{
	const int nParam = (NumberOfTargetScatter > 0) ? NumberOfTargetScatter : 1;

	// bus 输出通道数由连接到该端口的 bus 通道数决定。
	// 为避免未连接通道导致越界，只对实际存在的通道写出；
	// 正常验证时应让 Pos 和 ScatterRCS 都连接 NumberOfTargetScatter 个通道。
	const int nPosBus = Pos.GetSize();
	const int nRcsBus = ScatterRCS.GetSize();

	const int nPosWrite = std::min(nParam, nPosBus);
	const int nRcsWrite = std::min(nParam, nRcsBus);

	for (int i = 0; i < nPosWrite; ++i)
	{
		const Vec3 p = (i < static_cast<int>(positions.size()))
			? positions[static_cast<std::size_t>(i)]
			: make_vec_(0.0, 0.0, 0.0);

		SystemVueModelBuilder::DoubleMatrix m(3, 1);
		m(0, 0) = p.x;
		m(1, 0) = p.y;
		m(2, 0) = p.z;

		Pos[i][0U] = m;
	}

	for (int i = 0; i < nRcsWrite; ++i)
	{
		const double r = (i < static_cast<int>(rcsValues.size()))
			? rcsValues[static_cast<std::size_t>(i)]
			: 0.0;

		ScatterRCS[i][0U] = r;
	}
}

bool RADAR_TargetScatterLocation::Setup()
{
	if (NumberOfTargetScatter <= 0)
		NumberOfTargetScatter = 1;

	sampleIndex_ = 0ULL;
	motionAccumEcef_ = make_vec_(0.0, 0.0, 0.0);
	userPathIndex_ = 0U;

	// Pos / ScatterRCS 是真正的 bus 输出端口。
	// bus 通道数由 SystemVue 连接关系决定；这里不再用 SetRate() 模拟多通道。
	// 每个已连接的 bus 通道每次 Run() 输出 1 个 token。

	if (!validate_params_())
		return false;

	// 初始化 ECI 模式使用的坐标常量。
	const double lonDeg = get_array_value_(Position_Initial, Position_InitialSize, 0, 0.0);
	const double latDeg = get_array_value_(Position_Initial, Position_InitialSize, 1, 0.0);
	const double h = get_array_value_(Position_Initial, Position_InitialSize, 2, 0.0);

	lonRad_ = lonDeg * kDegToRad;
	latRad_ = latDeg * kDegToRad;

	p0Ecef_ = lla_to_ecef_(lonRad_, latRad_, h);

	const double sinLon = std::sin(lonRad_);
	const double cosLon = std::cos(lonRad_);
	const double sinLat = std::sin(latRad_);
	const double cosLat = std::cos(latRad_);

	eastEcef_ = make_vec_(-sinLon, cosLon, 0.0);
	northEcef_ = make_vec_(-sinLat * cosLon, -sinLat * sinLon, cosLat);
	upEcef_ = make_vec_(cosLat * cosLon, cosLat * sinLon, sinLat);

	load_user_file_();

	return true;
}

bool RADAR_TargetScatterLocation::Run()
{
	const int n = (NumberOfTargetScatter > 0) ? NumberOfTargetScatter : 1;

	if (Trajectory_Mode == User_Defined)
	{
		UserSample out = lastUserSample_;
		if (!userPath_.empty())
		{
			if (userPathIndex_ < userPath_.size())
			{
				out = userPath_[userPathIndex_];
				lastUserSample_ = out;
				++userPathIndex_;
			}
			else
			{
				out = lastUserSample_;
			}
		}

		write_outputs_(out.pos, out.rcs);
		++sampleIndex_;
		return true;
	}

	if (Trajectory_Mode == SimpleXYZ_Frame)
	{
		const double k = static_cast<double>(sampleIndex_);
		const double t = k * TimeStep;
		const double t2 = t * t;
		const double t3 = t2 * t;

		const double x0 = get_array_value_(Position_Initial_XYZ, Position_Initial_XYZSize, 0, 0.0);
		const double y0 = get_array_value_(Position_Initial_XYZ, Position_Initial_XYZSize, 1, 20e3);
		const double z0 = get_array_value_(Position_Initial_XYZ, Position_Initial_XYZSize, 2, 5e3);

		const double vx = get_array_value_(Velocity_Initial_XYZ, Velocity_Initial_XYZSize, 0, 0.0);
		const double vy = get_array_value_(Velocity_Initial_XYZ, Velocity_Initial_XYZSize, 1, 0.0);
		const double vz = get_array_value_(Velocity_Initial_XYZ, Velocity_Initial_XYZSize, 2, 0.0);

		const double ax = get_array_value_(Accelerate_XYZ, Accelerate_XYZSize, 0, 0.0);
		const double ay = get_array_value_(Accelerate_XYZ, Accelerate_XYZSize, 1, 0.0);
		const double az = get_array_value_(Accelerate_XYZ, Accelerate_XYZSize, 2, 0.0);

		const double jx = get_array_value_(Jerk_XYZ, Jerk_XYZSize, 0, 0.0);
		const double jy = get_array_value_(Jerk_XYZ, Jerk_XYZSize, 1, 0.0);
		const double jz = get_array_value_(Jerk_XYZ, Jerk_XYZSize, 2, 0.0);

		const Vec3 center = make_vec_(
			x0 + vx * t + 0.5 * ax * t2 + (jx * t3 / 3.0),
			y0 + vy * t + 0.5 * ay * t2 + (jy * t3 / 3.0),
			z0 + vz * t + 0.5 * az * t2 + (jz * t3 / 3.0)
		);

		std::vector<Vec3> positions;
		std::vector<double> rcsValues;
		positions.reserve(static_cast<std::size_t>(n));
		rcsValues.reserve(static_cast<std::size_t>(n));

		for (int i = 0; i < n; ++i)
		{
			const Vec3 sc = get_scatter_loc_(i);
			positions.push_back(add_(center, sc));
			rcsValues.push_back(calc_scatter_rcs_(i, sampleIndex_));
		}

		write_outputs_(positions, rcsValues);
		++sampleIndex_;
		return true;
	}

	// --------- ECI_Frame ---------
	const double rollDeg = Roll[0];
	const double pitchDeg = Pitch[0];
	const double yawDeg = Yaw[0];

	const double roll = rollDeg * kDegToRad;
	const double pitch = pitchDeg * kDegToRad;
	const double yaw = yawDeg * kDegToRad;

	const double cosRoll = std::cos(roll);
	const double sinRoll = std::sin(roll);
	const double cosPitch = std::cos(pitch);
	const double sinPitch = std::sin(pitch);
	const double cosYaw = std::cos(yaw);
	const double sinYaw = std::sin(yaw);

	// 质心运动方向复用 RADAR_Platform：yaw=0 指向 North，yaw=+90 指向 East，pitch=+90 指向 Up。
	const double dirEast = cosPitch * sinYaw;
	const double dirNorth = cosPitch * cosYaw;
	const double dirUp = sinPitch;

	Vec3 dirEcef = add_(
		add_(scale_(eastEcef_, dirEast), scale_(northEcef_, dirNorth)),
		scale_(upEcef_, dirUp)
	);

	const double norm2 = dot_(dirEcef, dirEcef);
	if (norm2 > 0.0)
		dirEcef = scale_(dirEcef, 1.0 / std::sqrt(norm2));

	const double stepDistance =
		Velocity_Initial * TimeStep
		+ 0.5 * Accelerate_Initial * TimeStep * TimeStep;

	motionAccumEcef_ = add_(motionAccumEcef_, scale_(dirEcef, stepDistance));

	double randomDistance = 0.0;
	if (IsRandomError == RandomError_true && Accelerate_Variance > 0.0)
	{
		randomDistance = std::sqrt(Accelerate_Variance) * base_random_position_(sampleIndex_);
	}

	const Vec3 centerMovedEcef = add_(
		p0Ecef_,
		add_(motionAccumEcef_, scale_(dirEcef, randomDistance))
	);

	const double theta = kEarthRotationRate * static_cast<double>(sampleIndex_) * TimeStep;

	std::vector<Vec3> positions;
	std::vector<double> rcsValues;
	positions.reserve(static_cast<std::size_t>(n));
	rcsValues.reserve(static_cast<std::size_t>(n));

	for (int i = 0; i < n; ++i)
	{
		const Vec3 sc = get_scatter_loc_(i);

		// 黑盒对齐：ECI_Frame 下 ScatterLoc 是 body frame 坐标。
		// body 轴定义：x=forward, y=right, z=down。
		// 局部坐标采用 NED：North, East, Down。
		// 先使用 Roll/Pitch/Yaw 将 ScatterLoc 从 body frame 旋转到局部 NED frame。
		const double sxBody = sc.x;
		const double syBody = sc.y;
		const double szBody = sc.z;

		const double nLoc =
			cosPitch * cosYaw * sxBody
			+ (sinRoll * sinPitch * cosYaw - cosRoll * sinYaw) * syBody
			+ (cosRoll * sinPitch * cosYaw + sinRoll * sinYaw) * szBody;

		const double eLoc =
			cosPitch * sinYaw * sxBody
			+ (sinRoll * sinPitch * sinYaw + cosRoll * cosYaw) * syBody
			+ (cosRoll * sinPitch * sinYaw - sinRoll * cosYaw) * szBody;

		const double dLoc =
			-sinPitch * sxBody
			+ sinRoll * cosPitch * syBody
			+ cosRoll * cosPitch * szBody;

		// NED -> ECEF：
		// N 对应 northEcef_，E 对应 eastEcef_，D 对应 -upEcef_。
		// 再与质心 ECEF 坐标相加，最后整体旋转到 ECI。
		const Vec3 scatterOffsetEcef = add_(
			add_(scale_(northEcef_, nLoc), scale_(eastEcef_, eLoc)),
			scale_(upEcef_, -dLoc)
		);

		const Vec3 scatterEcef = add_(centerMovedEcef, scatterOffsetEcef);
		const Vec3 pos = rotate_z_(scatterEcef, theta);

		positions.push_back(pos);
		rcsValues.push_back(calc_scatter_rcs_(i, sampleIndex_));
	}

	write_outputs_(positions, rcsValues);
	++sampleIndex_;
	return true;
}