RADAR_TargetScatterLocation::Vec3 RADAR_TargetScatterLocation::make_vec_(double x, double y, double z)
{
	Vec3 v;
	v.x = x;
	v.y = y;
	v.z = z;
	return v;
}

RADAR_TargetScatterLocation::Vec3 RADAR_TargetScatterLocation::add_(const Vec3& a, const Vec3& b)
{
	return make_vec_(a.x + b.x, a.y + b.y, a.z + b.z);
}

RADAR_TargetScatterLocation::Vec3 RADAR_TargetScatterLocation::scale_(const Vec3& a, double s)
{
	return make_vec_(a.x * s, a.y * s, a.z * s);
}

double RADAR_TargetScatterLocation::dot_(const Vec3& a, const Vec3& b)
{
	return a.x * b.x + a.y * b.y + a.z * b.z;
}

RADAR_TargetScatterLocation::Vec3 RADAR_TargetScatterLocation::lla_to_ecef_(double lonRad, double latRad, double h)
{
	// 黑盒对齐版 LLA -> ECEF。与 RADAR_Platform 对齐版本保持一致。
	const double a = kEarthSemiMajorAxis;
	const double b = kEarthSemiMinorAxis;

	const double a2 = a * a;
	const double b2 = b * b;
	const double e2 = 1.0 - b2 / a2;

	const double sinLat = std::sin(latRad);
	const double cosLat = std::cos(latRad);
	const double sinLon = std::sin(lonRad);
	const double cosLon = std::cos(lonRad);

	const double N = a / std::sqrt(1.0 - e2 * sinLat * sinLat);

	const double x = (N + h) * cosLat * cosLon;
	const double y = (N + h) * cosLat * sinLon;
	const double z = (N * (1.0 - e2) + h) * sinLat;

	return make_vec_(x, y, z);
}

RADAR_TargetScatterLocation::Vec3 RADAR_TargetScatterLocation::rotate_z_(const Vec3& v, double theta)
{
	const double c = std::cos(theta);
	const double s = std::sin(theta);

	return make_vec_(
		c * v.x - s * v.y,
		s * v.x + c * v.y,
		v.z
	);
}

bool RADAR_TargetScatterLocation::validate_params_() const
{
	const int n = (NumberOfTargetScatter > 0) ? NumberOfTargetScatter : 1;

	if (Trajectory_Mode == ECI_Frame || Trajectory_Mode == SimpleXYZ_Frame)
	{
		if (ScatterLocSize != 3 * n)
		{
			std::cerr << "RADAR_TargetScatterLocation: The size of ScatterLoc should have 3*NumberOfTargetScatter elements and 3 elements for each target scatter." << std::endl;
			return false;
		}

		if (RCSSize != n)
		{
			std::cerr << "RADAR_TargetScatterLocation: The number of ScatterLoc Size should be kept consistent with the RCS_Size" << std::endl;
			return false;
		}
	}

	return true;
}

void RADAR_TargetScatterLocation::init_empty_user_sample_()
{
	const int n = (NumberOfTargetScatter > 0) ? NumberOfTargetScatter : 1;
	lastUserSample_.pos.assign(static_cast<std::size_t>(n), make_vec_(0.0, 0.0, 0.0));
	lastUserSample_.rcs.assign(static_cast<std::size_t>(n), 0.0);
}

bool RADAR_TargetScatterLocation::load_user_file_()
{
	userPath_.clear();
	userPathIndex_ = 0U;
	init_empty_user_sample_();

	const int n = (NumberOfTargetScatter > 0) ? NumberOfTargetScatter : 1;

	if (FileName == nullptr || FileName[0] == '\0')
		return true;

	std::ifstream fin(FileName);
	if (!fin)
		return true;

	std::string line;
	while (std::getline(fin, line))
	{
		std::istringstream iss(line);
		UserSample sample;
		sample.pos.reserve(static_cast<std::size_t>(n));
		sample.rcs.reserve(static_cast<std::size_t>(n));

		bool ok = true;
		for (int i = 0; i < n; ++i)
		{
			double x = 0.0;
			double y = 0.0;
			double z = 0.0;
			double r = 0.0;
			if (!(iss >> x >> y >> z >> r))
			{
				ok = false;
				break;
			}
			sample.pos.push_back(make_vec_(x, y, z));
			sample.rcs.push_back(r);
		}

		if (ok && static_cast<int>(sample.pos.size()) == n)
			userPath_.push_back(sample);
	}

	if (!userPath_.empty())
		lastUserSample_ = userPath_.front();

	return true;
}

RADAR_TargetScatterLocation::Vec3 RADAR_TargetScatterLocation::get_scatter_loc_(int idx) const
{
	return make_vec_(
		get_array_value_(ScatterLoc, ScatterLocSize, 3 * idx + 0, 0.0),
		get_array_value_(ScatterLoc, ScatterLocSize, 3 * idx + 1, 0.0),
		get_array_value_(ScatterLoc, ScatterLocSize, 3 * idx + 2, 0.0)
	);
}

double RADAR_TargetScatterLocation::get_rcs_base_(int idx) const
{
	return get_array_value_(RCS, RCSSize, idx, 1.0);
}

